import { mkdtempSync, readFileSync, rmSync, readdirSync, lstatSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { prepareCandidate, verifyCandidate } from './candidate-artifact.mjs';
import { fileURLToPath } from 'node:url';
const temp=mkdtempSync(join(tmpdir(),'psst-pack-'));
const run=(command,args,options={})=>{const r=spawnSync(command,args,{encoding:'utf8',env:{...process.env,npm_config_cache:join(temp,'npm-cache')},...options});if(r.status!==0)throw new Error(`${command} failed: ${r.stderr}`);return r.stdout;};
try {
 const sourceRoot=fileURLToPath(new URL('../',import.meta.url)),artifactRoot=process.env.PSST_CANDIDATE_DIR??join(temp,'candidate');
 const candidate=process.env.PSST_CANDIDATE_DIR?verifyCandidate({sourceRoot,artifactRoot}):prepareCandidate({sourceRoot,artifactRoot});
 const packed=[{...candidate.evidence.package,filename:candidate.evidence.tarball.filename}];
 assert.equal(packed[0].name, '@matuto-ai/antigravity-psst-connector');
 const entries=packed[0].files.map(x=>x.path);
 for(const path of ['bin/psst-antigravity.mjs','src/connector.mjs','src/pairing.mjs','vendor/psst/enrollment.mjs','docs/pairing.md','vendor/psst/reference/inbox.mjs','vendor/psst/LICENSE'])assert(entries.includes(path));
 for(const path of ['bin/psst-antigravity-native.mjs','scripts/prepare-native-plugin.mjs','src/native-plugin.mjs','src/native-installation.mjs','src/native-binding.mjs','src/native-process-waiter.mjs','docs/native-pilot.md'])assert(entries.includes(path));
 assert(!entries.some(x=>/node_modules|test\/|\.sqlite|connection\.json|(^|\/)token$|\.github/.test(x)));
 for(const path of ['plugin.json','mcp_config.json','hooks.json','skills/psst-setup/SKILL.md','skills/psst/SKILL.md','src/approval-manager.mjs','vendor/psst/approval.mjs','vendor/psst/approval-source.json','docs/setup.md'])assert(entries.includes(path));
 const install=resolve(candidate.packageRoot,'../../..');
 const executable=join(candidate.packageRoot,'bin','psst-antigravity.mjs');
 assert.match(run(process.execPath,[executable,'--help'],{cwd:temp}),/cooperative stdio MCP/);
 const doctor=JSON.parse(run(process.execPath,[executable,'doctor'],{cwd:temp,env:{...process.env,HOME:temp}}));
 assert.equal(doctor.package_version,packed[0].version);assert.equal(doctor.package_shape,'verified');
 assert.equal(doctor.native_installation,'registration_or_package_absent');
 assert.equal(doctor.managed_registration.enabled,'not_checked');assert.equal(doctor.import_permission,'not_checked');assert.equal(doctor.owner_lock,'not_checked');assert.match(doctor.next_action,/^\/plugin install /);
 assert(lstatSync(join(doctor.plugin_directory,'plugin.json')).isFile());
 const running=JSON.parse(run(process.execPath,['--input-type=module','-e',`
   import { PassThrough, Writable } from 'node:stream';
   import { CONNECTOR_RUNTIME } from ${JSON.stringify(pathToFileURL(join(doctor.plugin_directory,'src/runtime-info.mjs')).href)};
   import { serveStdio } from ${JSON.stringify(pathToFileURL(join(doctor.plugin_directory,'src/mcp-stdio.mjs')).href)};
   const input=new PassThrough(),frames=[];
   const output=new Writable({write(bytes,encoding,done){frames.push(JSON.parse(bytes.toString()));done();}});
   const server=serveStdio({input,output,tools:{}});
   input.write(JSON.stringify({jsonrpc:'2.0',id:1,method:'initialize',params:{protocolVersion:'2025-06-18',capabilities:{},clientInfo:{name:'pack-smoke',version:'1'}}})+'\\n');
   await server.flush();await server.close();
   console.log(JSON.stringify({runtime:CONNECTOR_RUNTIME,serverInfo:frames[0].result.serverInfo}));
 `],{cwd:temp,env:{...process.env,HOME:temp}}));
 assert.deepEqual(running.runtime,{name:packed[0].name,version:packed[0].version});
 assert.deepEqual(running.serverInfo,{name:'antigravity-broker-connector',version:packed[0].version});
 const generator=join(install,'node_modules','.bin','psst-antigravity-native-plugin');
 const generated=JSON.parse(run(generator,[join(temp,'native-plugin'),'--experimental-native'],{cwd:temp}));
 assert.equal(generated.installed,false);
 const mcp=JSON.parse(readFileSync(join(generated.pluginDirectory,'mcp_config.json'),'utf8'));
 assert.equal(mcp.mcpServers.psst.args[2],'--experimental-native');
 assert(lstatSync(mcp.mcpServers.psst.args[0]).isFile());
 verifyCandidate({sourceRoot,artifactRoot});
 console.log(JSON.stringify({package:packed[0].name,version:packed[0].version,source_commit:candidate.evidence.source.commit,source_tree:candidate.evidence.source.tree,source_dirty:candidate.evidence.source.dirty,artifact_sha256:candidate.evidence.tarball.sha256,packed_runtime:'verified'}));
 console.log('Packed install and executable smoke passed with no sibling broker checkout.');
} finally {rmSync(temp,{recursive:true,force:true});}
